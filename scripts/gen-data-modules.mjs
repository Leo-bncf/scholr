#!/usr/bin/env node
/**
 * Generate a data module per table for the long tail of entities.
 *
 *   node scripts/gen-data-modules.mjs /tmp/schema.tsv
 *
 * The important domains (classes, gradebook, attendance, submissions, …) are
 * hand-written and are never overwritten — this only fills in the tables that
 * are essentially config: policies, rooms, periods, templates and so on.
 *
 * Each generated module exposes named school-scoped helpers plus a `where()`
 * escape hatch. `where()` exists so the base44 migration could finish without
 * hand-converting several hundred call sites at once; prefer adding a named
 * query when you touch one of these.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = resolve(ROOT, 'src/data');

// Hand-written — never regenerate these.
const HAND_WRITTEN = new Set([
  '_query', 'session', 'schools', 'memberships', 'classes', 'academics',
  'assignments', 'gradebook', 'attendance', 'submissions', 'demoRequests',
  'admin', 'functions', 'storage',
]);

// Tables already covered by a hand-written module, or not addressable as an
// ordinary table from the browser.
const COVERED_TABLES = new Set([
  'schools', 'school_memberships', 'classes', 'subjects', 'academic_years',
  'terms', 'cohorts', 'assignments', 'grade_items', 'predicted_grades',
  'attendance_records', 'submissions', 'demo_requests', 'audit_logs',
  'platform_config', 'profiles', 'school_stats',
]);

const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
// Table -> module name, singularised where the plural reads oddly as a module.
const moduleName = (table) => camel(table);

const rows = readFileSync(process.argv[2] ?? '/tmp/schema.tsv', 'utf8')
  .split('\n')
  .filter(Boolean)
  .map((line) => {
    const [table, cols] = line.split('\t');
    return { table: table.trim(), columns: cols.split(',').map((c) => c.trim()) };
  });

let written = 0;
const index = [];

for (const { table, columns } of rows) {
  if (COVERED_TABLES.has(table)) continue;

  const name = moduleName(table);
  if (HAND_WRITTEN.has(name)) continue;

  const file = resolve(DATA, `${name}.js`);
  const hasSchool = columns.includes('school_id');
  // created_by / updated_at are set by the database, never sent by the client.
  const selectable = columns.filter((c) => c !== 'updated_at' && c !== 'created_by');

  const orderCol = columns.includes('name')
    ? 'name'
    : columns.includes('date')
      ? 'date'
      : 'created_at';
  const ascending = orderCol !== 'created_at' && orderCol !== 'date';

  const src = `import { supabase } from '@/lib/supabase';
import { rows, maybeOne, one, none } from './_query';

/**
 * ${table}
 *
 * GENERATED by scripts/gen-data-modules.mjs. Safe to edit — regeneration skips
 * any module listed as hand-written in that script, so promote this file there
 * before making substantial changes.
 *
 * RLS decides what a caller can see; these functions do not re-check roles.
 */

const COLUMNS = '${selectable.join(', ')}';
${
  hasSchool
    ? `
/** Everything in a school. */
export function listForSchool(schoolId) {
  return rows(
    supabase.from('${table}').select(COLUMNS).eq('school_id', schoolId)
      .order('${orderCol}', { ascending: ${ascending} }),
    '${name}.listForSchool',
  );
}
`
    : `
/** Every row the caller can see. */
export function list() {
  return rows(
    supabase.from('${table}').select(COLUMNS).order('${orderCol}', { ascending: ${ascending} }),
    '${name}.list',
  );
}
`
}
export function get(id) {
  return maybeOne(supabase.from('${table}').select(COLUMNS).eq('id', id), '${name}.get');
}

/**
 * Equality filters, for call sites that don't have a named query yet.
 *
 * \`where({ school_id, status })\` maps each key to \`.eq()\`; an array value
 * becomes \`.in()\` and null becomes \`.is(null)\`. Prefer adding a named
 * function above when the same filter shows up more than once.
 */
export function where(filters = {}, { order, ascending = false, limit } = {}) {
  let q = supabase.from('${table}').select(COLUMNS);
  for (const [key, value] of Object.entries(filters)) {
    if (value === undefined) continue;
    if (value === null) q = q.is(key, null);
    else if (Array.isArray(value)) q = q.in(key, value);
    else q = q.eq(key, value);
  }
  if (order) q = q.order(order, { ascending });
  if (limit) q = q.limit(limit);
  return rows(q, '${name}.where');
}

export function create(record) {
  return one(supabase.from('${table}').insert(record).select(COLUMNS), '${name}.create');
}

export function update(id, patch) {
  return one(
    supabase.from('${table}').update(patch).eq('id', id).select(COLUMNS),
    '${name}.update',
  );
}

export function remove(id) {
  return none(supabase.from('${table}').delete().eq('id', id), '${name}.remove');
}
`;

  writeFileSync(file, src);
  index.push({ table, name });
  written += 1;
}

console.log(`${written} modules written`);
for (const { table, name } of index) console.log(`  ${table.padEnd(26)} -> src/data/${name}.js`);
